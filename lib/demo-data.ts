/** Build a full app User from an authorization profile. */
export function userFromProfile(id: string, email: string, p: UserProfile): User {
  return {
    id,
    name: p.name,
    email,
    role: p.role,
    avatarInitials: initials(p.name),
    warehouseIds: p.warehouseIds,
  };
}

function initials(name: string): string {
  const parts = name.trim().split(/\s+/).filter(Boolean);
  if (!parts.length) return "U";
  if (parts.length === 1) return parts[0].slice(0, 2).toUpperCase();
  return (parts[0][0] + parts[parts.length - 1][0]).toUpperCase();
}

/** Convenience: find a demo profile by email (case-insensitive). */
export function demoProfileByEmail(email: string) {
  const key = email.trim().toLowerCase();
  return demoAccounts.find((a) => a.email.toLowerCase() === key);
}

